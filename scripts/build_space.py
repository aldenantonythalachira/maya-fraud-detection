"""Assemble the Maya website into dist/space/ and publish it for hosting.

Copies what the site needs -- src/*.py, frontend/, the trained model bundle,
serve.py, the Dockerfile, render.yaml, README and slim requirements -- into one
folder. The trained weights go only into dist/ (gitignored) and the deploy
target, never into the team's GitHub repository.

    python scripts/build_space.py                          # build dist/space/ only
    python scripts/build_space.py --github USER/maya-site  # build + push to a private
                                                           # deploy repo (Render watches it)
    python scripts/build_space.py --upload USER/maya       # build + upload to a Hugging
                                                           # Face Space (Docker needs PRO)

--github uses the logged-in `gh` CLI, creates the repository as private if it
doesn't exist, and force-pushes a fresh snapshot each time (the repository only
holds deploy output). See docs/DEPLOY_SPACE.md.

Run locally the way the host runs it:
    cd dist/space && python serve.py        # port $PORT or 7860
"""

from __future__ import annotations

import argparse
import os
import shutil
import stat
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEPLOY = ROOT / "deploy" / "space"
MODEL_FILES = ["xgb_model.json", "conformal.json", "model_meta.json", "attack_results.json"]
REQUIRED_MODEL_FILES = MODEL_FILES[:2]


def _force_remove(func, path, _exc):
    """rmtree helper: git marks its object files read-only, which Windows refuses
    to delete; clear the flag and retry."""
    os.chmod(path, stat.S_IWRITE)
    func(path)


def build(out: Path) -> list[str]:
    missing = [f for f in REQUIRED_MODEL_FILES if not (ROOT / "models" / f).exists()]
    if missing:
        raise SystemExit(f"models/ is missing {missing}: build the model first (see README).")
    if out.exists():
        shutil.rmtree(out, onexc=_force_remove)  # a previous --github run left a .git here
    (out / "src").mkdir(parents=True)
    for py in sorted((ROOT / "src").glob("*.py")):
        shutil.copy2(py, out / "src" / py.name)
    shutil.copytree(ROOT / "frontend", out / "frontend")
    (out / "models").mkdir()
    copied = []
    for name in MODEL_FILES:
        src = ROOT / "models" / name
        if src.exists():
            shutil.copy2(src, out / "models" / name)
            copied.append(name)
    for name in ("Dockerfile", "README.md", "requirements.txt", "serve.py", "render.yaml"):
        shutil.copy2(DEPLOY / name, out / name)
    return copied


def push_github(out: Path, repo: str) -> None:
    """Commit dist/space as a fresh snapshot and force-push it to a private repo."""
    def run(*cmd, check=True):
        return subprocess.run(cmd, cwd=out, check=check, capture_output=True, text=True)

    if run("gh", "repo", "view", repo, check=False).returncode != 0:
        run("gh", "repo", "create", repo, "--private",
            "--description", "Maya demo website deploy bundle (generated by scripts/build_space.py)")
        print(f"[build_space] created private repository {repo}")
    run("git", "init", "-q", "-b", "main")
    run("git", "add", "-A")
    run("git", "commit", "-q", "-m", "Deploy Maya website (generated by scripts/build_space.py)")
    run("git", "remote", "add", "origin", f"https://github.com/{repo}.git")
    run("git", "push", "-q", "--force", "origin", "main")
    print(f"[build_space] pushed to https://github.com/{repo} (main)")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Build (and optionally upload) the Maya Space.")
    ap.add_argument("--out", default=str(ROOT / "dist" / "space"))
    ap.add_argument("--upload", metavar="USER/SPACE", default=None,
                    help="upload to this Hugging Face Space (created if missing)")
    ap.add_argument("--github", metavar="USER/REPO", default=None,
                    help="push the bundle to this private GitHub repository (for Render)")
    ap.add_argument("--private", action="store_true",
                    help="create the Space as private (only your account can open it); "
                         "switch it to public later in the Space settings")
    args = ap.parse_args(argv)
    out = Path(args.out)
    copied = build(out)
    size = sum(f.stat().st_size for f in out.rglob("*") if f.is_file()) / 1e6
    print(f"[build_space] wrote {out} ({size:.1f} MB; models: {', '.join(copied)})")
    if "attack_results.json" not in copied:
        print("[build_space] note: no models/attack_results.json -> the Robustness tab will say how to "
              "generate it (python src/attack_sim.py --json-out models/attack_results.json)")
    if args.github:
        push_github(out, args.github)
    if not args.upload:
        return 0
    try:
        from huggingface_hub import HfApi
    except ImportError:
        print("pip install huggingface_hub, then run `hf auth login`", file=sys.stderr)
        return 2
    hf = HfApi()
    hf.create_repo(args.upload, repo_type="space", space_sdk="docker", exist_ok=True, private=args.private)
    hf.upload_folder(repo_id=args.upload, repo_type="space", folder_path=str(out),
                     commit_message="Deploy Maya website")
    owner, name = args.upload.split("/", 1)
    print(f"[build_space] uploaded. Space: https://huggingface.co/spaces/{args.upload}")
    print(f"[build_space] site: https://{owner.lower()}-{name.lower().replace('_', '-')}.hf.space/demo/"
          + ("  (private: only your logged-in account can open it)" if args.private else ""))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
